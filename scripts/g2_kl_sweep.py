"""Order study with a KL anchor: does a KL penalty stop distill-then-RL from reward hacking?

Arms (image flow toy, CPU only), each run for every kl_coef and seed:
  A: GRPO on the SFT teacher (10-step SDE), KL to the teacher
  B: GRPO on the DMD2 4-step student (renoise), KL to the distilled student
Both use LoRA, so the reference policy is the same network with LoRA disabled. Every run is scored at 4 and 10 NFE
against the SFT teacher and the table reports mean +- std over seeds.

Prerequisites: runs/image_flow_grpo/sft/final and runs/distill/image_flow_dmd2/distill/final.
Usage:
    uv run python scripts/g2_kl_sweep.py [--kl 0 0.01 0.1 1 10] [--seeds 0 1 2] [--out docs/results/g2_kl_sweep.md]
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
from diffusion_omni.core.config import load_config
from diffusion_omni.core.registry import discover_plugins
from diffusion_omni.posttrain.rl.trainer import RLTrainer
from diffusion_omni.reward.scorecard import run_scorecard

TEACHER = "runs/image_flow_grpo/sft/final"
STUDENT = "runs/distill/image_flow_dmd2/distill/final"
ARMS = {
    "A_rl_teacher": ("configs/image_flow_grpo.yaml", [f"rl.init_from={TEACHER}"]),
    "B_distill_then_rl": (f"{STUDENT}/config.yaml", [f"rl.init_from={STUDENT}", "rl.epochs=40",
                                                     "rl.lora={rank: 8, alpha: 16}"]),
}
HEADER = """# Order study with a KL anchor: full table

Generated by `scripts/g2_kl_sweep.py`. Image flow toy, CPU. Mean ± std over {seeds} seeds, n = {n} samples per row,
scored against the SFT teacher at 32 ODE steps. A runs natively at 10 steps and B at 4; the other NFE is off-policy.
"final kl" is the mean per-step KL to the reference over the last 5 epochs.

"""
COLS = ["reward", "fd", "precision", "recall", "class_acc", "shape_err", "center_tv", "diversity"]


def train(arm: str, kl: float, seed: int, root: Path) -> str:
    out = root / f"{arm}_kl{kl:g}_s{seed}"
    final = out / "rl" / "final"
    if not (final / "model.pt").exists():
        path, overrides = ARMS[arm]
        cfg = load_config(path, overrides + ["device=cpu", f"seed={seed}", f"output_dir={out}",
                                             f"rl.algorithm.kl_coef={kl}"])
        RLTrainer(cfg).train()
    return str(final)


def last_kl(ckpt: str) -> float:
    rows = [json.loads(line) for line in (Path(ckpt).parent / "log.jsonl").read_text().splitlines()]
    vals = [r["kl"] for r in rows[-5:] if "kl" in r]
    return float(np.mean(vals)) if vals else 0.0


def table(rows: list[dict], kls: dict[str, float]) -> str:
    groups = defaultdict(list)
    for r in rows:
        if r["model"].startswith(("A_", "B_")):
            arm, kl, _ = r["model"].rsplit("_", 2)
            groups[(arm, float(kl[2:]), r["nfe"])].append(r)
    ref = {r["nfe"]: r for r in rows if r["model"] == "reference"}
    lines = ["| arm | kl_coef | nfe | final kl | " + " | ".join(COLS) + " |", "|" + "---|" * (len(COLS) + 4)]
    for nfe, r in sorted(ref.items()):
        lines.append(f"| teacher (ODE) | n/a | {nfe} | | " + " | ".join(f"{r[c]:.3g}" for c in COLS) + " |")
    for (arm, kl, nfe), rs in sorted(groups.items()):
        cells = []
        for c in COLS:
            v = np.array([r[c] for r in rs])
            cells.append(f"{v.mean():.3g} ± {v.std():.2g}")
        fk = np.mean([kls[r["model"]] for r in rs])
        lines.append(f"| {arm} | {kl:g} | {nfe} | {fk:.3g} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kl", type=float, nargs="+", default=[0.0, 0.01, 0.1, 1.0, 10.0])
    ap.add_argument("--seeds", type=int, nargs="+", default=[0, 1, 2])
    ap.add_argument("--arms", nargs="+", default=list(ARMS))
    ap.add_argument("-n", type=int, default=512)
    ap.add_argument("--root", default="runs/g2/kl_sweep")
    ap.add_argument("--out", default="docs/results/g2_kl_sweep.md")
    args = ap.parse_args()
    discover_plugins()
    root = Path(args.root)
    ckpts = {f"{arm}_kl{kl:g}_s{seed}": train(arm, kl, seed, root)
             for arm in args.arms for kl in args.kl for seed in args.seeds}
    kls = {k: last_kl(v) for k, v in ckpts.items()}
    rows = run_scorecard(TEACHER, ckpts, nfes=(4, 10), n=args.n, seed=0)
    (root / "scorecard.json").write_text(json.dumps(rows, indent=1))
    md = HEADER.format(n=args.n, seeds=len(args.seeds)) + table(rows, kls)
    Path(args.out).write_text(md + "\n")
    print(md)


if __name__ == "__main__":
    main()
