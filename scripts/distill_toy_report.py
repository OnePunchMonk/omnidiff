"""Score every toy distillation run against its teacher and write docs/results/distillation_toy.md.

Prerequisites (CPU, minutes each):
    uv run omnidiff sft -c configs/<teacher>.yaml           for the four teachers
    uv run omnidiff distill -c configs/distill/<name>.yaml  for each student below
Usage:
    uv run python scripts/distill_toy_report.py [-n 512]
"""

from __future__ import annotations

import argparse
from pathlib import Path

from omnidiff.reward.scorecard import run_scorecard, save, to_markdown

GROUPS = {
    "image_flow_grpo": ["image_flow_kd", "image_flow_consistency", "image_flow_flow_map", "image_flow_dmd2",
                        "image_flow_dmd2_gan", "image_flow_rcm"],
    "image_ddpm_ddpo": ["image_ddpm_dmd2"],
    "video_flow_grpo": ["video_flow_dmd2", "video_flow_flow_map"],
    "text_masked_grpo": ["text_masked_kd", "text_masked_sdtt", "text_masked_coupled_kd"],
}
# Tuned baselines: the teacher with a sharper or different sampler, at the same step counts.
VARIANTS = {
    "image_flow_grpo": {"renoise": ["process.sampler=renoise"], "shift3": ["process.shift=3.0"]},
    "image_ddpm_ddpo": {"renoise": ["process.sampler=renoise"]},
    "video_flow_grpo": {"renoise": ["process.sampler=renoise"], "shift3": ["process.shift=3.0"]},
    "text_masked_grpo": {"T0.8": ["process.temperature=0.8"], "T0.6": ["process.temperature=0.6"]},
}
DROP = {"colour_err"}

HEADER = """# Few-step distillation on the toy tasks

Generated by `scripts/distill_toy_report.py`. Everything is CPU-only: tiny DiTs (dim 128, depth 4) on synthetic data
whose generating process is known exactly. These numbers check that the methods behave as the literature says they
should, relative to each other and to tuned baselines. They are not claims about real-scale models.

Setup: n = {n} samples per row, the same prompts for every row, NFE in {{{nfe}}}. `reference@32` is the teacher with
its deterministic sampler at 32 steps, and every teacher-relative metric is measured against it. `reference` rows
are the undistilled teacher at few steps. `reference[...]` rows are the teacher with a tuned sampler (another
sampler, time shift or temperature). Students should be judged against the best of these, not the default.

| column | meaning | better |
|---|---|---|
| fd, precision, recall | Fréchet distance and k-NN precision/recall (k = 3) against `reference@32`, in fixed random features | low, high, high |
| data_fd, data_precision, data_recall | the same against real data samples | low, high, high |
| diversity | mean pairwise RMS distance between samples sharing a prompt (text: share of distinct samples) | close to the reference |
| class_acc, direction_acc | the oracle says the sample shows the prompted colour or motion direction | high |
| shape_err, motion_err | distance from the best single blob / from a straight constant-speed track | low |
| center_tv | total variation between blob-centre histograms of samples and data (mode coverage) | low |
| valid, coverage | text: share of samples that are exact corpus lines / share of prompt-consistent lines produced | high |
| reward | the teacher config's RL reward, for reference | n/a |
| ms_per_sample | wall-clock on CPU | low |

"""  # kept in the JSON, left out of the doc tables for width


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", type=int, default=512)
    ap.add_argument("--nfe", type=int, nargs="+", default=[1, 2, 4, 8])
    ap.add_argument("--out", default="docs/results/distillation_toy.md")
    args = ap.parse_args()
    sections = []
    for teacher, students in GROUPS.items():
        ckpts = {s: f"runs/distill/{s}/distill/final" for s in students if Path(f"runs/distill/{s}/distill/final").exists()}
        rows = run_scorecard(f"runs/{teacher}/sft/final", ckpts, args.nfe, args.n, variants=VARIANTS.get(teacher))
        save(rows, f"runs/scorecards/{teacher}")
        rows = [{k: v for k, v in r.items() if k not in DROP} for r in rows]
        sections.append(f"### Teacher `{teacher}`\n\n{to_markdown(rows)}\n")
        print(sections[-1], flush=True)
    Path(args.out).write_text(HEADER.format(n=args.n, nfe=", ".join(map(str, args.nfe))) + "\n".join(sections))
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
